const { test, expect } = require('@playwright/test')
const fs = require('node:fs'), path = require('node:path')
require('./layout-fixture.cjs')
for (const [width,height] of [[1920,1080],[1440,900]]) test(`arrival stays closed through missing predictions at ${width}`, async ({page}) => {
  await page.setViewportSize({width,height})
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.clock.install({time:new Date('2026-01-01T00:00:00Z')})
  await page.clock.pauseAt(new Date('2026-01-01T00:00:01Z'))
  await page.goto('/tests/arrival-harness.html?scan=0')
  await expect.poll(()=>page.evaluate(()=>!!window.arrival)).toBe(true)
  const card=page.locator('.hud-arrival')
  await page.evaluate(()=>window.arrival.update('still',{cam:'on'}))
  await page.clock.runFor(1800)
  await expect(page.getByTestId('arrival-detail')).toHaveText('Camera teaching')
  await page.clock.runFor(4000)
  await expect(card).toBeHidden()
  await page.evaluate(()=>window.arrival.update('still',{pred:null,router:'S-home'}))
  await page.clock.runFor(300)
  await expect(card).toBeHidden()
  await expect(page.getByTestId('judge-headline')).toHaveText('Recalibrating')
  if(process.env.HUD_SCREENSHOTS) { fs.mkdirSync(process.env.HUD_SCREENSHOTS,{recursive:true}); await page.screenshot({path:path.join(process.env.HUD_SCREENSHOTS,`${width}-recalibrating.png`)}) }
  await page.evaluate(()=>window.arrival.update('still',{pred:null,router:'S-W30'}))
  await expect(card).toBeHidden()
  await page.evaluate(()=>{window.arrival.update('empty');window.arrival.event('reset')})
  await page.clock.runFor(300)
  await expect(card).toBeVisible()
  await expect(page.getByTestId('arrival-title')).toHaveText('Nobody is here.')
  await page.evaluate(()=>window.arrival.update('still',{cam:'off'}))
  await page.clock.runFor(1800)
  await expect(page.getByTestId('arrival-detail')).toHaveText('0 cameras')
  await page.clock.runFor(4000)
  await page.evaluate(()=>window.arrival.update('blind'))
  await page.clock.runFor(300)
  await expect(card).toBeVisible()
  await expect(page.getByTestId('arrival-title')).toHaveText('Sensor blind')
  await page.evaluate(()=>window.arrival.update('empty',{},true))
  await page.clock.runFor(300)
  await expect(page.getByTestId('arrival-title')).toHaveText('No data')
  await page.evaluate(()=>window.arrival.update('empty',{armed:true}))
  await page.clock.runFor(300)
  await expect(page.getByTestId('arrival-title')).toHaveText('Armed.')
})
