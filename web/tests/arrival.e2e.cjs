// The card over the live hall (#552): it says what it shows, so the room rests on the hall and flies down on time.
async function overHall(page, options = {}) {
  await page.setViewportSize({ width: options.width ?? 1920, height: options.height ?? 1080 })
  if (options.reduced) await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.clock.install({ time: new Date('2026-01-01T00:00:00Z') })
  await page.clock.pauseAt(new Date('2026-01-01T00:00:01Z'))
  await page.goto('/tests/arrival-harness.html')
  await expect.poll(() => page.evaluate(() => !!window.arrival)).toBe(true)
  await page.evaluate(() => { window.phases = []; window.cuts = []; addEventListener('hud:arrival', event => { window.phases.push(event.detail.state); if (event.detail.cut) window.cuts.push(event.detail.cut) }) })
  await page.clock.runFor(300)
}
const phase = page => page.evaluate(() => document.documentElement.dataset.hudArrival)
test('waiting shows the room beside readable words, and found fades the card as the room flies', async ({ page }) => {
  await overHall(page)
  const card = page.locator('.hud-arrival')
  expect(await phase(page)).toBe('waiting')
  await expect(page.locator('#room')).toHaveAttribute('data-arrival', 'waiting')
  await expect(card).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  // With the rail, the words sit on the page colour inside it, never over the room. On the one spot the hall is
  // the whole screen: the words sit on it, inside the screen, and the card's footer is not drawn.
  const hall = await page.evaluate(() => document.documentElement.dataset.judgeLayout === 'hall')
  for (const part of hall ? ['h1', '[data-testid="arrival-detail"]'] : ['h1', '[data-testid="arrival-detail"]', 'footer']) {
    const box = await card.locator(part).boundingBox()
    expect(box.x + box.width).toBeLessThanOrEqual(hall ? page.viewportSize().width - 400 : 640)
  }
  if (hall) await expect(card.locator('footer')).toBeHidden()
  await expect(page.locator('.room-legend')).toBeHidden()
  await capture(page, '1920-over-hall-waiting')
  await page.evaluate(() => window.arrival.update('still'))
  await page.clock.runFor(1500 + 1100)
  await expect(page.getByTestId('arrival-title')).toHaveText('Found you.')
  expect(await phase(page)).toBe('waiting') // the words hold first: no fly behind a card that still covers it
  await expect(card.locator('.arrival-message')).toHaveCSS('opacity', '1')
  await page.clock.runFor(200)
  expect(await phase(page)).toBe('found')
  await expect(page.locator('#room')).toHaveAttribute('data-arrival', 'found')
  await expect(page.locator('.room-legend')).toBeVisible({ visible: !hall })
  for (const [ms, name] of [[400, 'fly-1'], [600, 'fly-2'], [600, 'fly-3']]) {
    await page.clock.runFor(ms)
    expect(Number(await card.locator('.arrival-message').evaluate(el => getComputedStyle(el).opacity))).toBeLessThan(1)
    if (process.env.HUD_SCREENSHOTS) await page.screenshot({ path: path.join(process.env.HUD_SCREENSHOTS, `1920-over-hall-${name}.png`) })
  }
  await page.clock.runFor(300)
  await expect(card).toBeHidden()
  expect(await page.evaluate(() => window.phases)).toEqual(['found', 'closed'])
  // It does not come back by itself for the same visitor.
  await page.evaluate(() => window.arrival.update('empty'))
  await page.clock.runFor(300)
  await page.evaluate(() => window.arrival.update('still'))
  await page.clock.runFor(4000)
  await expect(card).toBeHidden()
  expect(await page.evaluate(() => window.phases)).toEqual(['found', 'closed'])
})
test('armed waits over the room, and an intrusion goes straight to the floor in the fault colour', async ({ page }) => {
  await overHall(page)
  await page.evaluate(() => window.arrival.update('empty', { armed: true }))
  await page.clock.runFor(300)
  expect(await phase(page)).toBe('waiting')
  await page.evaluate(() => { window.arrival.update('still', { armed: true }); window.arrival.event('intrusion') })
  await page.clock.runFor(300)
  await expect(page.getByTestId('arrival-title')).toHaveText('Someone is here.')
  await expect(page.getByTestId('arrival-title')).toHaveCSS('color', 'rgb(242, 85, 90)')
  expect(await phase(page)).toBe('closed')
  await expect(page.locator('.hud-arrival')).toBeVisible()
  await expect(page.locator('.hud-arrival')).toHaveCSS('opacity', '1')
  // The room is told to jump to the floor, not to fly (#552): the same closed state, with cut.
  expect(await page.evaluate(() => [document.documentElement.dataset.hudArrivalCut, window.cuts])).toEqual(['1', [true]])
  await capture(page, '1920-over-hall-intrusion')
  await page.evaluate(() => { window.arrival.event('disarmed'); window.arrival.update('empty') })
  await page.clock.runFor(300)
  expect(await page.evaluate(() => [document.documentElement.dataset.hudArrival, document.documentElement.dataset.hudArrivalCut])).toEqual(['waiting', undefined])
})
test('a replay moves the card aside and it comes back afterwards', async ({ page }) => {
  await overHall(page)
  await expect(page.getByTestId('arrival-title')).toHaveText('Nobody is here.')
  await page.evaluate(() => { document.documentElement.dataset.hudReplay = 'on' })
  await expect(page.locator('.hud-arrival')).toBeHidden()
  expect(await phase(page)).toBe('closed')
  expect(await page.locator('#hud').evaluate(el => el.inert)).toBe(false)
  await page.evaluate(() => { document.documentElement.dataset.hudReplay = '' })
  await expect(page.locator('.hud-arrival')).toBeVisible()
  expect(await phase(page)).toBe('waiting')
})
test('reduced motion still hands over, and the operator can skip the card', async ({ page }) => {
  await overHall(page, { reduced: true })
  await page.evaluate(() => window.arrival.update('still'))
  await page.clock.runFor(1500 + 1300)
  expect(await phase(page)).toBe('found')
  await page.clock.runFor(1800)
  await expect(page.locator('.hud-arrival')).toBeHidden()
  await page.evaluate(() => { window.arrival.update('empty'); window.arrival.event('reset') })
  await page.clock.runFor(300)
  expect(await phase(page)).toBe('waiting')
  await page.keyboard.press('o')
  expect(await phase(page)).toBe('closed')
  await page.getByTestId('skip-arrival').click()
  await page.keyboard.press('Escape')
  await page.clock.runFor(300)
  await expect(page.locator('.hud-arrival')).toBeHidden()
  expect(await phase(page)).toBe('closed')
})

// Foot traffic (#584, #586): a person walking past must not flash "Found you." or raise the alarm.
test('a 1 s presence is not greeted, a 2 s presence is', async ({ page }) => {
  await overHall(page)
  const title = page.getByTestId('arrival-title')
  await page.evaluate(() => window.arrival.update('still'))
  for (let i = 0; i < 10; i++) {
    await page.clock.runFor(100)
    await expect(title).toHaveText('Nobody is here.')
    await expect(title).toHaveCSS('opacity', '1') // no flicker either
  }
  await page.evaluate(() => window.arrival.update('empty'))
  await page.clock.runFor(2000)
  await expect(title).toHaveText('Nobody is here.')
  expect(await phase(page)).toBe('waiting')
  await page.evaluate(() => window.arrival.update('still'))
  await page.clock.runFor(1400)
  await expect(title).toHaveText('Nobody is here.')
  await page.clock.runFor(600)
  await expect(title).toHaveText('Found you.')
})
for (const [width, height] of [[1920, 1080], [1440, 900]]) {
  test(`armed: passed by is one calm line, an intrusion is the alarm, at ${width}`, async ({ page }) => {
    await overHall(page, { width, height })
    const title = page.getByTestId('arrival-title')
    const line = page.getByTestId('arrival-passed')
    await page.evaluate(() => window.arrival.update('empty', { armed: true }))
    await page.clock.runFor(1000)
    // The headline's own text-in runs on the real clock: let it finish before its place is read.
    const settled = () => page.evaluate(() => Promise.all(document.getAnimations().filter(a => a.effect?.getTiming().iterations !== Infinity).map(a => a.finished.catch(() => null))))
    await settled()
    const top = (await title.boundingBox()).y
    // Someone appears while armed: the card waits for the board to say which it was.
    await page.evaluate(() => window.arrival.update('still', { armed: true }))
    await page.clock.runFor(1000)
    await expect(title).toHaveText('Armed.')
    const zone = await page.evaluate(() => window.arrival.peek('still').pred.zone)
    await page.evaluate(zone => { window.arrival.update('empty', { armed: true }); window.arrival.event('passed_by', undefined, { zone }) }, zone)
    await page.clock.runFor(1000)
    await expect(title).toHaveText('Armed.')
    await expect(title).not.toHaveCSS('color', 'rgb(242, 85, 90)')
    await expect(line).toHaveText(/^Someone passed by (on the (left|right)|in the bathroom|at the desk)$/)
    await expect(line).toHaveCSS('color', 'rgb(154, 163, 173)')
    await expect(line).toHaveCSS('font-size', '28px')
    await settled()
    expect((await title.boundingBox()).y).toBe(top) // nothing moved to make room for it
    await capture(page, `${width}-passed-by`)
    await page.clock.runFor(4500)
    await expect(line).toHaveText('')
    await page.evaluate(() => { window.arrival.update('still', { armed: true }); window.arrival.event('intrusion') })
    await page.clock.runFor(300)
    await expect(title).toHaveText('Someone is here.')
    await expect(title).toHaveCSS('color', 'rgb(242, 85, 90)')
    await capture(page, `${width}-intrusion`)
  })
}
