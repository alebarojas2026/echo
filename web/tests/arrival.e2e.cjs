const { test, expect } = require('@playwright/test')
const path = require('node:path')
const shots = process.env.HUD_SCREENSHOTS
async function capture(page, name) {
  await expect(page.getByTestId('arrival-title')).toHaveCSS('opacity', '1')
  await expect(page.getByTestId('arrival-detail')).toHaveCSS('opacity', '1')
  if (shots) await page.screenshot({ path: path.join(shots, name + '.png') })
}
for (const [width, height] of [[1920,1080], [1440,900]]) {
  test(`arrival, safety states and commands at ${width}`, async ({ page }) => {
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.setViewportSize({ width, height })
    await page.clock.install({ time: new Date('2026-01-01T00:00:00Z') })
    await page.clock.pauseAt(new Date('2026-01-01T00:00:01Z'))
    await page.goto('/tests/arrival-harness.html')
    await expect.poll(() => page.evaluate(() => !!window.arrival)).toBe(true)
    const title = page.getByTestId('arrival-title')
    await page.clock.runFor(300)
    await expect(title).toHaveText('Nobody is here.')
    await capture(page, `${width}-empty`)
    await page.evaluate(() => { window.arrival.event('enter', 'one'); window.arrival.event('enter', 'one'); window.arrival.update('still') })
    await page.clock.runFor(300)
    await expect(title).toHaveText('Found you.')
    await expect(page.getByTestId('arrival-detail')).toHaveText('0 cameras')
    await expect(page.getByTestId('visitor-count')).toHaveText('Visitor 1')
    await capture(page, `${width}-found`)
    await page.clock.runFor(2600)
    await expect(title).toBeVisible()
    await page.clock.runFor(100)
    await expect(page.locator('.hud-arrival')).toBeHidden()
    await expect(page.getByTestId('judge-headline')).toBeVisible()
    expect(await page.locator('#hud').evaluate(el => el.getBoundingClientRect().x)).toBe(0)
    await expect(page.locator('body')).toHaveCSS('background-color', 'rgb(17, 19, 22)')
    await page.evaluate(() => window.arrival.update('empty', { armed: true }))
    await page.clock.runFor(300)
    await expect(title).toHaveText('Armed.')
    await capture(page, `${width}-armed`)
    await page.evaluate(() => window.arrival.event('intrusion'))
    await page.clock.runFor(300)
    await expect(title).toHaveText('Someone is here.')
    await expect(title).toHaveCSS('color', 'rgb(242, 85, 90)')
    await capture(page, `${width}-intrusion`)
    await page.evaluate(() => window.arrival.update('empty', { armed: true }))
    await expect(title).toHaveText('Someone is here.')
    await page.evaluate(() => window.arrival.update('blind', { armed: true }))
    await page.clock.runFor(300)
    await expect(title).toHaveText('Sensor blind')
    await capture(page, `${width}-blind`)
    await page.evaluate(() => window.arrival.update('empty', {}, true))
    await page.clock.runFor(300)
    await expect(title).toHaveText('No data')
    await capture(page, `${width}-no-data`)
    await page.evaluate(() => { window.arrival.update('empty'); window.arrival.event('reset') })
    await page.clock.runFor(300)
    await expect(title).toHaveText('Nobody is here.')
    await expect(page.getByTestId('visitor-count')).toHaveText('Visitor 1')
    await page.keyboard.press('o')
    await expect(page.locator('.hud-arrival')).toBeHidden()
    await page.getByRole('button', { name: 'Arm space', exact: true }).click()
    expect(await page.evaluate(() => window.arrival.commands)).toEqual([{ cmd: 'arm', args: { on: true } }])
    await page.evaluate(() => window.arrival.update('empty', { armed: true }))
    await page.getByRole('button', { name: 'Disarm space', exact: true }).click()
    expect(await page.evaluate(() => window.arrival.commands[1])).toEqual({ cmd: 'arm', args: { on: false } })
    await page.keyboard.press('Escape')
    await expect(page.locator('.hud-arrival')).toBeVisible()
    expect(errors).toEqual([])
  })
}
test('camera wording, cancelled handoff and disposal', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.clock.install({ time: new Date('2026-01-01T00:00:00Z') })
    await page.clock.pauseAt(new Date('2026-01-01T00:00:01Z'))
  await page.goto('/tests/arrival-harness.html')
  await expect.poll(() => page.evaluate(() => !!window.arrival)).toBe(true)
  await page.evaluate(() => window.arrival.update('still', { cam: 'on' }))
  await expect(page.getByTestId('arrival-detail')).toHaveText('Camera teaching')
  await page.evaluate(() => window.arrival.update('blind'))
  await page.clock.fastForward(4000)
  await expect(page.getByTestId('arrival-title')).toHaveText('Sensor blind')
  await page.evaluate(() => window.arrival.dispose())
  await expect(page.locator('.hud-arrival')).toHaveCount(0)
})
