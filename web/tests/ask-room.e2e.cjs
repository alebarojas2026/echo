const { test, expect } = require('@playwright/test')
const path = require('node:path')
for (const [width, height] of [[1920,1080], [1440,900], [768,900], [320,700]]) {
  test(`question, waiting, answer and fallback at ${width}`, async ({ page }) => {
    await page.setViewportSize({ width, height })
    await page.clock.install({ time: new Date('2026-01-01T00:00:00Z') })
    await page.clock.pauseAt(new Date('2026-01-01T00:00:01Z'))
    await page.goto('/?mock=still')
    await page.clock.runFor(3600)
    await page.getByRole('button', { name: 'Ask the room', exact: true }).click()
    const input = page.getByLabel('Your question')
    await expect(input).toBeFocused()
    await page.getByRole('button', { name: 'Was anyone here in the last 10 minutes?', exact: true }).click()
    await expect(page.getByTestId('ask-progress')).toHaveText('Reading the room records…')
    await expect(page.getByRole('button', { name: 'Ask', exact: true })).toBeDisabled()
    if (process.env.HUD_SCREENSHOTS && width >= 1440) await page.screenshot({ path: path.join(process.env.HUD_SCREENSHOTS, `${width}-waiting.png`) })
    await page.clock.runFor(650)
    await expect(page.getByTestId('ask-answer')).toHaveText('No room records are loaded in this mock.')
    await expect(page.getByTestId('ask-rows')).toContainText('source: Mock event store')
    await expect(page.getByTestId('ask-time')).toHaveText('Mock response time: __ ms')
    await expect(page.getByTestId('ask-privacy')).toHaveText('Mock response · __ bytes out')
    const box = await page.locator('dialog').boundingBox()
    expect(box.x).toBeGreaterThanOrEqual(0)
    expect(box.x + box.width).toBeLessThanOrEqual(width)
    if (process.env.HUD_SCREENSHOTS && width >= 1440) await page.screenshot({ path: path.join(process.env.HUD_SCREENSHOTS, `${width}-answer.png`) })
    await input.fill('What is the weather tomorrow?')
    await input.press('Enter')
    await page.clock.runFor(650)
    await expect(page.getByTestId('ask-answer')).toContainText('I can answer:')
    await expect(page.getByTestId('ask-rows')).toBeHidden()
    await page.keyboard.press('Escape')
    await expect(page.locator('dialog')).not.toBeVisible()
    await expect(page.getByRole('button', { name: 'Ask the room', exact: true })).toBeFocused()
    await page.keyboard.press('/')
    await expect(input).toBeFocused()
    await input.fill('A slash')
    await input.press('/')
    await expect(input).toHaveValue('A slash/')
  })
}
async function fixture(page, mode = 'board') {
  await page.goto('/src/hud/index.html')
  await page.evaluate(async mode => {
    const { mountAskRoom } = await import('/src/hud/ask-room.ts')
    document.body.innerHTML = '<header></header>'
    window.pending = []
    window.dispose = mountAskRoom(document.querySelector('header'), { mode, ask(question, signal) {
      return new Promise((resolve, reject) => window.pending.push({ question, signal, resolve, reject }))
    } })
  }, mode)
  await page.keyboard.press('/')
}
test('board evidence is text, measured zero is retained, failures can retry', async ({ page }) => {
  await page.route('**/proof.json', route => route.fulfill({ json: { bytes_out: 0 } }))
  await fixture(page)
  const input = page.getByLabel('Your question')
  await input.fill('Was anyone here?')
  await input.press('Enter')
  await page.evaluate(() => window.pending[0].resolve({ answer: 'A recorded entry is available.', rows: [{ event: '<img src=x onerror=alert(1)>', zone: 'Desk' }], tool: 'presence', ms: 0 }))
  await expect(page.getByTestId('ask-rows')).toContainText('<img src=x onerror=alert(1)>')
  await expect(page.locator('dialog img')).toHaveCount(0)
  await expect(page.getByTestId('ask-time')).toHaveText('Answer time: 0 ms')
  await expect(page.getByTestId('ask-privacy')).toHaveText('Answered on the board · 0 bytes out')
  await input.press('Enter')
  await page.evaluate(() => window.pending[1].reject(new Error('offline')))
  await expect(page.getByTestId('ask-error')).toHaveText('The room could not answer. Try the question again.')
  await expect(page.getByRole('button', { name: 'Ask', exact: true })).toBeEnabled()
})
test('closing cancels work and a late answer cannot replace a new one', async ({ page }) => {
  await fixture(page, 'mock')
  const input = page.getByLabel('Your question')
  await input.fill('Old question')
  await input.press('Enter')
  await page.keyboard.press('Escape')
  expect(await page.evaluate(() => window.pending[0].signal.aborted)).toBe(true)
  await page.keyboard.press('/')
  await input.fill('New question')
  await input.press('Enter')
  await page.evaluate(() => window.pending[1].resolve({ answer: 'New answer', rows: [], tool: null, ms: null }))
  await page.evaluate(() => window.pending[0].resolve({ answer: 'Old answer', rows: [], tool: null, ms: null }))
  await expect(page.getByTestId('ask-answer')).toHaveText('New answer')
  await page.evaluate(() => window.dispose())
  await expect(page.locator('dialog')).toHaveCount(0)
})
