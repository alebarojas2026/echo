const {test,expect}=require('@playwright/test')
const fs=require('node:fs'),path=require('node:path')
const {layout}=require('./layout-fixture.cjs')
for(const [width,height] of [[1920,1080],[1440,900]]) test(`blind words and tamper priority at ${width}`,async({page})=>{
 await page.setViewportSize({width,height});await page.emulateMedia({reducedMotion:'reduce'});await page.clock.install()
 await page.goto('/tests/arrival-harness.html?scan=0')
 await page.evaluate(()=>{window.healthEvents=[];window.addEventListener('hud:health',e=>window.healthEvents.push(e.detail))})
 const blind=layout.links.filter(l=>l.tx==='east'||l.rx==='east').map(l=>l.id)
 await page.evaluate(blind=>window.arrival.update('blind',{health:{status:'blind',blind,reason:'rate'}}),blind)
 const sentence='East beacon not heard. Check its power.'
 await expect(page.getByTestId('arrival-detail')).toHaveText(sentence)
 await expect(page.getByTestId('judge-detail')).toContainText(sentence)
 await expect(page.getByTestId('judge-detail')).toContainText('Alerts are paused')
 expect(await page.evaluate(()=>window.healthEvents.at(-1).sentence)).toBe(sentence)
 await expect(page.locator('#hud')).toHaveAttribute('data-health-sentence',sentence)
 const shot=async name=>{if(process.env.HUD_SCREENSHOTS){fs.mkdirSync(process.env.HUD_SCREENSHOTS,{recursive:true});await page.screenshot({path:path.join(process.env.HUD_SCREENSHOTS,`${width}-${name}.png`)})}}
 await shot('blind')
 await page.evaluate(blind=>window.arrival.update('blind',{armed:true,tamper:['east'],health:{status:'blind',blind,reason:'rate'}}),blind)
 await expect(page.locator('.hud-arrival')).toBeHidden()
 await expect(page.getByTestId('judge-headline')).toHaveText('East beacon unplugged while armed')
 await expect(page.getByTestId('judge-headline')).toHaveCSS('color','rgb(242, 85, 90)')
 await expect(page.getByTestId('judge-headline')).toHaveCSS('font-size','56px')
 await expect(page.getByTestId('judge-detail')).toHaveText('Sensor blind')
 await expect(page.getByTestId('tamper-alert')).toBeHidden()
 await shot('tamper')
 await page.evaluate(()=>window.arrival.update('empty',{armed:false,tamper:[]}))
 await expect(page.locator('#hud')).toHaveAttribute('data-health-sentence','')
})
