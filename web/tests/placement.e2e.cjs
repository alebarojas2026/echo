const {test,expect}=require('@playwright/test')
const fs=require('node:fs'),path=require('node:path')
const base=require('./fixtures/desk-layout.json')
const layout={...base,nodes:[{id:'one',name:'Window radio',xyz_m:[0,4,1]},{id:'two',name:'Door radio',xyz_m:[4,4,1]},{id:'three',name:'Reading desk',xyz_m:[2,0,1]}],links:[{id:'one>three:ble',tx:'one',rx:'three',kind:'ble'},{id:'two>three:wifi',tx:'two',rx:'three',kind:'wifi'},{id:'two>one:ble',tx:'two',rx:'one',kind:'ble'}]}
for(const [width,height] of [[1920,1080],[1440,900]])test(`placement check uses live links and layout at ${width}`,async({page})=>{
 await page.route('**/nodes.json',r=>r.fulfill({json:layout}))
 await page.setViewportSize({width,height});await page.emulateMedia({reducedMotion:'reduce'});await page.clock.install()
 await page.goto('/tests/arrival-harness.html?scan=0')
 const panel=page.getByTestId('placement-check')
 await expect(panel).toBeHidden()
 await page.keyboard.press('o');await expect(panel).toBeVisible()
 await page.evaluate(links=>{window.placementLinks=links;window.sendPlacement=(t,quiet,noisy,missing=false)=>window.arrival.update('empty',{src:'live',t,links:window.placementLinks.map((l,i)=>({id:l.id,dbm:-60,base_dbm:i===2?null:-60,drop_db:i===2?null:i===0?quiet:noisy,rate_hz:missing?0:8,expected_hz:8,status:missing?'stale':'ok',why:0}))});window.sendPlacement(10000,0,0)},layout.links)
 await expect(panel.getByTestId('placement-link')).toHaveCount(3)
 await expect(panel).toContainText('Window radio to Reading desk, Bluetooth')
 await expect(panel).toContainText('Door radio to Reading desk, Wi-Fi')
 await expect(panel.locator('[data-seen="true"]')).toHaveCount(0)
 await page.getByTestId('placement-measure').click()
 await page.evaluate(()=>{for(let i=1;i<=50;i++)window.sendPlacement(10000+i*100,i%2?0.1:-0.1,i%2?3:-3)})
 await page.clock.runFor(1000)
 await page.evaluate(()=>window.sendPlacement(16000,3,3))
 await expect(panel.locator('[data-seen="true"]')).toHaveCount(1)
 await expect(panel).toContainText('3.0 dB drop')
 await expect(panel).toContainText('Reading or baseline missing')
 await expect(panel).toContainText('8.0 readings/s')
 if(process.env.HUD_SCREENSHOTS){fs.mkdirSync(process.env.HUD_SCREENSHOTS,{recursive:true});await page.screenshot({path:path.join(process.env.HUD_SCREENSHOTS,`${width}-placement.png`)})}
 await page.evaluate(()=>window.sendPlacement(17000,9,9,true))
 await expect(panel.locator('[data-seen="true"]')).toHaveCount(0)
 await page.keyboard.press('Escape');await expect(panel).toBeHidden()
 await page.goto('/tests/arrival-harness.html?scan=0&op=1')
 await expect(panel).toBeVisible()
})
